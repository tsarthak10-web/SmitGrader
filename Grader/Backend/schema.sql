-- =====================================================================
-- GradeFlow High-Performance Database Architecture & Supabase Storage Setup
-- Run this script in your Supabase SQL Editor (Dashboard -> SQL Editor -> New Query)
-- =====================================================================

-- =====================================================================
-- 1. Layer C: Structured Grade Data (student_grades Table)
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.student_grades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number TEXT NOT NULL,
    course_code TEXT NOT NULL,
    course_name TEXT,
    credits NUMERIC(4, 2) DEFAULT 0.0,
    internal_marks TEXT,
    end_sem_marks TEXT,
    total_marks NUMERIC(5, 2),
    grade TEXT,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- B-Tree Index on registration_number:
-- Enables instant O(log N) indexed point-queries, eliminating the need for extra filters like branch.
CREATE INDEX IF NOT EXISTS idx_student_grades_reg 
ON public.student_grades(registration_number);

-- Deduplicate existing test data: removes duplicate rows from earlier test uploads,
-- keeping only the most recent entry for each student and course.
DELETE FROM public.student_grades a
USING public.student_grades b
WHERE a.registration_number = b.registration_number
  AND a.course_code = b.course_code
  AND a.ctid < b.ctid;

-- Idempotency Unique Index:
-- Prevents duplicate record spam if a student uploads the same transcript multiple times.
-- Enables PostgreSQL / Supabase UPSERT (ON CONFLICT DO UPDATE).
CREATE UNIQUE INDEX IF NOT EXISTS idx_student_course_unique 
ON public.student_grades(registration_number, course_code);


-- =====================================================================
-- 2. Layer B: Raw File Metadata Tracking (uploaded_files Table)
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.uploaded_files (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    registration_number TEXT NOT NULL,
    file_name TEXT NOT NULL,
    file_url TEXT,
    file_size BIGINT,
    mime_type TEXT,
    uploaded_at TIMESTAMPTZ DEFAULT now()
);

-- B-Tree Index on registration_number for instantaneous upload history retrieval
CREATE INDEX IF NOT EXISTS idx_uploaded_files_reg 
ON public.uploaded_files(registration_number);


-- =====================================================================
-- 3. Layer A: Supabase Storage Bucket ('transcripts') & Access Policies
-- =====================================================================
-- Enable public bucket named 'transcripts' for raw transcript storage (PDF/TXT)
INSERT INTO storage.buckets (id, name, public)
VALUES ('transcripts', 'transcripts', true)
ON CONFLICT (id) DO NOTHING;

-- Storage Policy: Allow public read access to download/view stored documents
CREATE POLICY "Public Read Access for Transcripts"
ON storage.objects FOR SELECT
USING (bucket_id = 'transcripts');

-- Storage Policy: Allow service role & authorized uploads to transcripts bucket
CREATE POLICY "Allow All Uploads to Transcripts"
ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'transcripts');

CREATE POLICY "Allow All Updates to Transcripts"
ON storage.objects FOR UPDATE
WITH CHECK (bucket_id = 'transcripts');


-- =====================================================================
-- 4. Enable Row Level Security (RLS) & Grant Access
-- =====================================================================
ALTER TABLE public.student_grades ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.uploaded_files ENABLE ROW LEVEL SECURITY;

-- Allow read and write for authenticated & service role keys
CREATE POLICY "Enable Read Access for All Users on student_grades" 
ON public.student_grades FOR SELECT USING (true);

CREATE POLICY "Enable Insert/Update for All Users on student_grades" 
ON public.student_grades FOR ALL USING (true);

CREATE POLICY "Enable Read Access for All Users on uploaded_files" 
ON public.uploaded_files FOR SELECT USING (true);

CREATE POLICY "Enable Insert/Update for All Users on uploaded_files" 
ON public.uploaded_files FOR ALL USING (true);

